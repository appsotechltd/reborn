"""Writes the logo R used as the first letter of the "Reborn" wordmark, for the app and the web.

The R is Fraunces SemiBold's own glyph (the same font as the wordmark), with the logo's candle flame
in its bowl (the flame from app/assets/brand/reborn-mark.svg, drawn larger to read at header size). Coordinates are font units
(2000 per em), y down, with the cap top at 0 and the baseline at 1400; the box is the glyph's
advance width (1504) wide.

Run from the repo root: python3 app/tool/wordmark_r.py  (needs fonttools)
Writes app/lib/src/theme/wordmark_r.dart and web/components/WordmarkR.tsx.
"""
from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

CAP, ADVANCE = 1400, 1504
f = TTFont("app/assets/fonts/Fraunces-SemiBold.ttf")
gs = f.getGlyphSet()
glyph = gs[f.getBestCmap()[ord("R")]]
assert glyph.width == ADVANCE


def n(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


class Rec(BasePen):
    def __init__(self, gs, xf):
        super().__init__(gs)
        self.ops, self.xf = [], xf

    def p(self, pt):
        return self.xf(*pt)

    def _moveTo(self, a): self.ops.append(("M", self.p(a)))
    def _lineTo(self, a): self.ops.append(("L", self.p(a)))
    def _qCurveToOne(self, a, b): self.ops.append(("Q", self.p(a), self.p(b)))
    def _curveToOne(self, a, b, c): self.ops.append(("C", self.p(a), self.p(b), self.p(c)))
    def _closePath(self): self.ops.append(("Z",))


r = Rec(gs, lambda x, y: (x, CAP - y))
glyph.draw(r)

# The flame paths from reborn-mark.svg, moved from its 1024 canvas into the glyph's units.
FLAME_OUTER = "M520 206 C540 292 614 348 614 440 C614 498 568 536 512 536 C456 536 410 498 410 440 C410 370 462 334 492 286 C506 264 516 238 520 206 Z"
FLAME_INNER = "M516 356 C526 404 562 432 562 474 C562 502 540 520 512 520 C484 520 462 502 462 474 C462 434 500 410 516 356 Z"
# The flame fills more of the bowl than in the app icon, so it still shows at header size.
K = 1.6
CX, CY = 800, 440  # where the flame's middle sits in the bowl


def flame(d):
    xf = lambda x, y: (CX + K * (x - 512), CY + K * (y - 371))
    toks, ops, i = d.replace("M", " M ").replace("C", " C ").replace("Z", " Z ").split(), [], 0
    while i < len(toks):
        t = toks[i]
        if t == "M":
            ops.append(("M", xf(float(toks[i + 1]), float(toks[i + 2])))); i += 3
        elif t == "C":
            pts = [xf(float(toks[i + 1 + 2 * k]), float(toks[i + 2 + 2 * k])) for k in range(3)]
            ops.append(("C", *pts)); i += 7
        else:
            ops.append(("Z",)); i += 1
    return ops


def svg_d(ops):
    return "".join(o[0] + " ".join(f"{n(x)} {n(y)}" for x, y in o[1:]) for o in ops)


def dart(ops, var):
    out = [f"  final {var} = Path();"]
    for o in ops:
        a = [f"{n(v)}" for pt in o[1:] for v in pt]
        out.append({"M": f"  {var}.moveTo({', '.join(a)});", "L": f"  {var}.lineTo({', '.join(a)});",
                    "Q": f"  {var}.quadraticBezierTo({', '.join(a)});", "C": f"  {var}.cubicTo({', '.join(a)});",
                    "Z": f"  {var}.close();"}[o[0]])
    return "\n".join(out)


outer, inner = flame(FLAME_OUTER), flame(FLAME_INNER)
HEADER = "Generated by app/tool/wordmark_r.py; edit that, not this."

open("app/lib/src/theme/wordmark_r.dart", "w").write(f"""// {HEADER}
import 'dart:ui';

/// Width and cap height of the logo R, in font units (2000 per em).
const double kWordmarkRAdvance = {ADVANCE};
const double kWordmarkRCap = {CAP};

/// The logo R's letter shape: cap top at y 0, baseline at y {CAP}.
Path wordmarkRGlyph() {{
{dart(r.ops, 'p')}
  return p;
}}

/// The candle flame in the R's bowl, and its pale core.
(Path, Path) wordmarkRFlame() {{
{dart(outer, 'o')}
{dart(inner, 'i')}
  return (o, i);
}}
""")

open("web/components/WordmarkR.tsx", "w").write(f"""// {HEADER}

/**
 * The logo R (Fraunces SemiBold's R with the candle flame in its bowl), used as the first letter
 * of the "Reborn" wordmark. It is cap height tall and sits on the text baseline, the letter in the
 * text colour and the flame in candle amber.
 */
export function WordmarkR() {{
  return (
    <svg
      viewBox="0 0 {ADVANCE} {CAP}"
      aria-hidden="true"
      focusable="false"
      style={{{{ display: "inline-block", height: "{CAP / 2000}em", width: "{ADVANCE / 2000}em", verticalAlign: "baseline", overflow: "visible" }}}}
    >
      <defs>
        <linearGradient id="wordmark-r-flame" x1="0" y1="0" x2="0" y2="1">
          <stop offset="0" stopColor="#F6C66E" />
          <stop offset="1" stopColor="#E9A23B" />
        </linearGradient>
      </defs>
      <path fill="currentColor" d="{svg_d(r.ops)}" />
      <path fill="url(#wordmark-r-flame)" d="{svg_d(outer)}" />
      <path fill="#FBE3B0" d="{svg_d(inner)}" />
    </svg>
  );
}}
""")
print("ok")
